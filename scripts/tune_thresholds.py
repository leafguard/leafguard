"""Threshold sweep script for LeafGuard (Task T5.2).

Reads `field_results.csv` generated by `scripts/field_eval.py`.
Sweeps CONF_OK (0.35 to 0.85) and CONF_LOW (0.15 to 0.55).
Prints the share of confident predictions, accuracy among confident predictions,
and share of unrecognised predictions for each pair.
Recommends nothing; provides empirical data for the team to choose and defend.
"""
import csv
import sys
from pathlib import Path


def main():
    root = Path(__file__).resolve().parent.parent
    csv_path = root / "field_results.csv"

    if not csv_path.exists():
        print(f"Error: '{csv_path}' not found.")
        print("Run `python scripts/field_eval.py` first to generate field results.")
        sys.exit(1)

    records = []
    with open(csv_path, "r", encoding="utf-8") as f:
        reader = csv.DictReader(f)
        for row in reader:
            records.append({
                "file": row["file"],
                "true": row["true"],
                "predicted": row["predicted"],
                "prob": float(row["prob"]),
            })

    total = len(records)
    if total == 0:
        print("No records found in field_results.csv")
        sys.exit(0)

    print(f"Loaded {total} field predictions from {csv_path.name}")
    print("\n================ THRESHOLD SWEEP GRID ================")
    print(f"{'CONF_OK':<9} {'CONF_LOW':<10} {'% Confident':<14} {'Acc (Conf)':<14} {'% Unrec':<10}")
    print("-" * 60)

    conf_ok_range = [round(x * 0.05, 2) for x in range(7, 18)]  # 0.35 to 0.85
    conf_low_range = [round(x * 0.05, 2) for x in range(3, 12)]  # 0.15 to 0.55

    for ok in conf_ok_range:
        for low in conf_low_range:
            if low >= ok:
                continue

            conf_count = 0
            conf_correct = 0
            unrec_count = 0

            for r in records:
                p = r["prob"]
                is_correct = (r["true"] == r["predicted"])

                if p >= ok:
                    conf_count += 1
                    if is_correct:
                        conf_correct += 1
                elif p < low:
                    unrec_count += 1

            pct_conf = (conf_count / total) * 100
            acc_conf = (conf_correct / conf_count * 100) if conf_count > 0 else 0.0
            pct_unrec = (unrec_count / total) * 100

            print(f"{ok:<9.2f} {low:<10.2f} {pct_conf:>5.1f}%         {acc_conf:>5.1f}%         {pct_unrec:>5.1f}%")

    print("======================================================")
    print("Note: The team chooses the operating point based on acceptable risk trade-off.")


if __name__ == "__main__":
    main()
